"""The eight research questions of ARCHITECTURE §13, simulation stage.

Each experiment runs a grid of scenarios on the same seeds (common random numbers), on both
backgrounds (the anchored default and pure zero intelligence, RISKS K21), and writes a generated
Markdown report to reports/rqN.md with every run's manifest beside it (reports/rqN.manifests.json).
The reports hold data and design only; docs/RESEARCH_RESULTS.md reads them.

    python -m hftsim.research all --seeds 8 --secs 180 --workers 6
    python -m hftsim.research rq2 rq7 --out some/dir --no-check
"""

from __future__ import annotations

import argparse
import datetime
import json
from pathlib import Path
from typing import Callable

from . import report, stats
from .runner import REPO, Scenario, decomposition, market_makers, run_many, verify

BACKGROUNDS = ("default", "zi")
LATENCIES = ("colocated", "proximity", "remote")
STEP7 = "step 7 (micro-price centre, GLFT quotes, online σ, order-flow skew)"


class Ctx:
    def __init__(self, seeds: int, first_seed: int, secs: int, warmup: int, workers: int | None, out: Path, check: bool):
        self.seeds = list(range(first_seed, first_seed + seeds))
        self.base = Scenario(secs=secs, warmup_secs=warmup)
        self.workers = workers
        self.out = out
        self.check = check
        self._verified: dict[str, bool] = {}

    def grid(self, scenarios: list[Scenario]) -> dict[Scenario, list[dict]]:
        jobs = [(s, seed) for s in scenarios for seed in self.seeds]
        results = run_many(jobs, workers=self.workers)
        out: dict[Scenario, list[dict]] = {}
        for (s, _), r in zip(jobs, results):
            out.setdefault(s, []).append(r)
        return out

    def design(self, text: str, pnl: bool = True) -> str:
        b = self.base
        money = (
            f" Agent PnL is the change in mark-to-market PnL over the window: a position held at {b.warmup_secs} s is "
            f"carried in at that moment's mid, and its revaluation is included in the inventory column."
            if pnl
            else ""
        )
        return (
            f"**Design.** {text} Each cell: seeds {self.seeds[0]}–{self.seeds[-1]} (the same seeds in every cell), "
            f"{b.secs} simulated seconds, everything measured over the window {b.warmup_secs}–{b.secs} s.{money} "
            f"Values are means over seeds with 95% Student-t intervals in brackets; money in dollars."
        )

    def write(self, name: str, title: str, question: str, body: list[str], res: dict[Scenario, list[dict]]) -> Path:
        self.out.mkdir(parents=True, exist_ok=True)
        manifests = [r["manifest"] for rs in res.values() for r in rs]
        (self.out / f"{name}.manifests.json").write_text(json.dumps(manifests, indent=1) + "\n", encoding="utf-8")
        first = next(iter(res.values()))[0]["manifest"]
        if self.check:
            if first["digest"] not in self._verified:
                self._verified[first["digest"]] = verify({"manifest": first})
            ok = self._verified[first["digest"]]
            check = f"the first run (seed {first['seed']}) was re-run without the cache and {'reproduced' if ok else 'DID NOT reproduce'} digest `{first['digest']}`."
        else:
            check = "not run for this report (`--no-check`)."
        repro = (
            f"**Reproducibility.** {len(manifests)} runs of hftsim {first['version']}. `{name}.manifests.json` holds each "
            f"run's complete flags and event digest; `hftsim run <flags>` reproduces the digest. Check: {check}"
        )
        stamp = datetime.date.today().isoformat()
        text = "\n\n".join([f"# {title}", f"*Generated by `python -m hftsim.research {name}` on {stamp}.*", report.SIMULATION_ONLY, f"**Question.** {question}", *body, repro])
        path = self.out / f"{name}.md"
        path.write_text(text + "\n", encoding="utf-8")
        return path


def _ci(xs: list, digits: int = 2) -> str:
    xs = [x for x in xs if x is not None]
    return report.ci(*stats.mean_ci(xs), digits=digits) if xs else "–"


def _sd(xs: list[float], digits: int = 2) -> str:
    return f"{stats.stdev(xs):.{digits}f}"


def _mm(r: dict) -> dict:
    return market_makers(r)[0]


def _pnl(rs: list[dict]) -> list[float]:
    """The first market maker's PnL in each run."""
    return [_mm(r)["pnl_dollars"] for r in rs]


def _paired(a: list[float], b: list[float], same: bool = False) -> str:
    """Mean of a − b over seeds with its paired t interval; 'baseline' for the reference cell."""
    return "baseline" if same else report.ci(*stats.paired_ci(a, b))


def _inv(d: dict) -> float:
    return d["inventory"] + d["carried"]


def _bg(b: str) -> str:
    return "zero-intelligence" if b == "zi" else "default"


def _verdict(lo: float, hi: float, above: str = "above zero", below: str = "below zero") -> str:
    return above if lo > 0 else (below if hi < 0 else "unclear")


def rq1(c: Ctx) -> Path:
    cells = [c.base.with_(makers=(5,), mm_gamma=g, informed=10) for g in (0.5, 1.75, 3.5, 7.0, 14.0)]
    cells += [c.base.with_(makers=(5,), mm_max_inventory=m, informed=10) for m in (4, 20)]
    cells += [c.base.with_(makers=(4,), informed=10)]
    cells = [s.with_(background=b) for b in BACKGROUNDS for s in cells]
    res = c.grid(cells)
    rows = []
    for s in cells:
        mms = [_mm(r) for r in res[s]]
        pnl = [m["pnl_dollars"] for m in mms]
        base = c.base.with_(background=s.background, makers=(5,), informed=10)
        d1 = [decomposition(m, 1000) for m in mms]
        rows.append([
            _bg(s.background), "A–S" if s.makers == (4,) else "GLFT", s.mm_gamma, s.mm_max_inventory * s.mm_unit_lots, _ci(pnl), _paired(pnl, _pnl(res[base]), s == base), _sd(pnl),
            _ci([d["spread_capture"] for d in d1]), _ci([d["adverse_selection"] for d in d1]), _ci([_inv(d) for d in d1]),
            _ci([m["stats"]["inventory_rms"] for m in mms], 1), max(m["stats"]["max_abs_position"] for m in mms), f"{stats.mean([m['fills'] for m in mms]):.0f}",
        ])
    # Control: the same comparison without informed traders, to see whether the effect of γ
    # depends on informed flow.
    control = [c.base.with_(background=b, makers=(5,), mm_gamma=g) for b in BACKGROUNDS for g in (3.5, 14.0)]
    cres = c.grid(control)
    crows = []
    for s in control:
        mms = [_mm(r) for r in cres[s]]
        base = s.with_(mm_gamma=3.5)
        d1 = [decomposition(m, 1000) for m in mms]
        crows.append([
            _bg(s.background), s.mm_gamma, _ci(_pnl(cres[s])), _paired(_pnl(cres[s]), _pnl(cres[base]), s == base),
            _ci([d["spread_capture"] for d in d1]), _ci([d["adverse_selection"] for d in d1]), _ci([_inv(d) for d in d1]),
            _ci([m["stats"]["inventory_rms"] for m in mms], 1),
        ])
    res = {**res, **cres}
    body = [
        c.design(
            "One market maker with 10 informed traders (signal noise 0.5 tick, proximity latency). GLFT quotes (ladder step 5: "
            "micro-price centre, closed-form GLFT spreads and skew, σ = 1 tick/√s, A = 130, k = 5) with risk aversion γ swept at "
            "an inventory limit of 50 shares, then the limit swept at γ = 3.5; last, the Avellaneda–Stoikov quotes (step 4, "
            "horizon 0.03 s) at γ = 3.5. A control repeats γ = 3.5 against γ = 14 without informed traders."
        ),
        report.table(
            ["background", "quotes", "γ", "limit (shares)", "PnL $", "PnL − baseline (paired) $", "PnL s.d. across seeds $", "spread capture $", "adverse selection (1 s) $", "inventory $", "inventory RMS (shares)", "max |position|", "fills"],
            rows,
        ),
        "Baseline: GLFT, γ = 3.5, limit 50 shares, same background; differences are paired on seed. Decomposition at a "
        "1 s horizon (ARCHITECTURE §8): spread capture + adverse selection + inventory − fees = PnL, exactly, in every "
        "run (no fees here).",
        "### Control: no informed traders",
        report.table(["background", "γ", "PnL $", "PnL − γ 3.5 (paired) $", "spread capture $", "adverse selection (1 s) $", "inventory $", "inventory RMS (shares)"], crows),
    ]
    return c.write("rq1", "RQ1: inventory risk and optimal quoting", "How does risk aversion (and the inventory limit) trade spread income against inventory risk?", body, res)


def rq2(c: Ctx) -> Path:
    cells = [c.base.with_(background=b, makers=(5,), informed=n, informed_noise=q) for b in BACKGROUNDS for q in (0.25, 1.0) for n in (0, 10, 30, 60)]
    res = c.grid(cells)
    rows = []
    for s in cells:
        mms = [_mm(r) for r in res[s]]
        d1, d15 = [decomposition(m, 1000) for m in mms], [decomposition(m, 15000) for m in mms]
        pnl = stats.mean_ci([m["pnl_dollars"] for m in mms])
        base = s.with_(informed=0)
        informed = [sum(a["pnl_dollars"] for a in r["agents"] if a["kind"] == "informed") for r in res[s]]
        rows.append([
            _bg(s.background), s.informed_noise, s.informed, report.ci(*pnl), _verdict(pnl[1], pnl[2]), _paired(_pnl(res[s]), _pnl(res[base]), s == base),
            _ci([d["spread_capture"] for d in d1]), _ci([d["adverse_selection"] for d in d1]), _ci([d["adverse_selection"] for d in d15]),
            _ci(informed) if s.informed else "–",
        ])
    body = [
        c.design(
            "One GLFT market maker (step 5) against 0, 10, 30 or 60 informed traders whose value signal carries Gaussian noise "
            "of 0.25 or 1 tick (latency in RQ5). Informed traders take liquidity with IOC orders when their estimate is at "
            "least 1 tick through the best quote."
        ),
        report.table(["background", "signal noise (ticks)", "informed traders", "maker PnL $", "PnL sign (95%)", "PnL − no informed (paired) $", "spread capture $", "adverse selection 1 s $", "adverse selection 15 s $", "informed traders' PnL $"], rows),
        "The break-even frontier is where the maker's PnL interval first lies wholly below zero as informed flow grows.",
    ]
    return c.write("rq2", "RQ2: when adverse selection makes market making unprofitable", "How much informed flow, of what quality, turns the market maker's PnL negative?", body, res)


def _queue_rows(results: list[dict]) -> list[list]:
    rows = []
    for k, b in enumerate(results[0]["market"]["queue_fill_touch"]):
        n = sum(r["market"]["queue_fill_touch"][k]["orders"] for r in results)
        f = sum(r["market"]["queue_fill_touch"][k]["any_fill"] for r in results)
        full = sum(r["market"]["queue_fill_touch"][k]["complete"] for r in results)
        hi = "∞" if b["max_ahead"] is None else b["max_ahead"]
        p, lo, up = stats.wilson_ci(f, n)
        rows.append([f"{b['min_ahead']}–{hi}", n, report.ci(100 * p, 100 * lo, 100 * up, 1) if n else "–", f"{100 * full / n:.1f}" if n else "–"])
    return rows


def rq3_and_6(c: Ctx) -> tuple[Path, Path]:
    cells = [c.base.with_(background=b, informed=n, ofi_ms=(100, 1000, 10000)) for b in BACKGROUNDS for n in (0, 30)]
    res = c.grid(cells)
    body3 = [
        c.design(
            "The background with 0 or 30 informed traders (two order-flow regimes) and no market maker. Every order that "
            "joined or improved the best price on its side, bucketed by the quantity already queued at that price when it "
            "arrived; pooled over seeds, Wilson 95% intervals; orders still resting at the end are left out (censored).",
            pnl=False,
        )
    ]
    for s in cells:
        body3 += [f"### {_bg(s.background)} background, {s.informed} informed traders", report.table(["quantity ahead (shares)", "orders", "filled at least partly (%)", "filled completely (%)"], _queue_rows(res[s]))]
    body3.append(
        "Not done here: the comparison with queue-reactive model predictions (Huang, Lehalle & Rosenbaum 2015) that "
        "ARCHITECTURE §13 lists; it needs that model's intensities estimated on these runs."
    )
    p3 = c.write("rq3", "RQ3: queue position and execution probability", "How does the chance of being filled fall with the queue ahead, and does order flow change it?", body3, res)
    rows = []
    for s in cells:
        for k, ms in enumerate(s.ofi_ms):
            fits = [r["market"]["ofi"][k] for r in res[s] if r["market"]["ofi"][k] is not None]
            rows.append([
                _bg(s.background), s.informed, f"{ms / 1000:g} s", f"{stats.mean([f['intervals'] for f in fits]):.0f}" if fits else "–",
                _ci([1e3 * f["beta_ticks_per_share"] for f in fits], 3), _ci([f["r2"] for f in fits], 3),
                _ci([f["depth_shares"] for f in fits], 0), _ci([f["beta_ticks_per_share"] * f["depth_shares"] for f in fits], 3),
            ])
    body6 = [
        c.design(
            "The background with 0 or 30 informed traders, no market maker. Over consecutive intervals of 0.1, 1 or 10 s, "
            "the mid change (ticks) is regressed on the order-flow imbalance of the best quotes (Cont, Kukanov & Stoikov "
            "2014), one regression per run.",
            pnl=False,
        ),
        report.table(["background", "informed traders", "interval", "intervals per run", "β (ticks per 1,000 shares)", "R²", "average top-of-book depth (shares)", "β × depth"], rows),
        "In CKS's stylised book (the same depth D at every level) ΔP = OFI / (2D), so β × depth ≈ 0.5; "
        "comparing the regimes checks whether β scales with 1/depth.",
        "### Return autocorrelation in the same runs (no market maker)",
        report.table(
            ["background", "informed traders", "lag-1 autocorrelation of 1 s returns", "variance ratio (10 s / 10 × 1 s)"],
            [[_bg(s.background), s.informed, _ci([r["market"]["return_acf1"] for r in res[s]], 3), _ci([r["market"]["variance_ratio_10"] for r in res[s]], 2)] for s in cells],
        ),
    ]
    p6 = c.write("rq6", "RQ6: order-flow imbalance and short-term price moves", "How much of the short-term mid change does order-flow imbalance explain, and how does its impact scale with depth?", body6, res)
    return p3, p6


def rq4(c: Ctx) -> Path:
    cells = [c.base.with_(background=b, makers=(7,), mm_latency=lat, arbs=arbs, informed=10) for b in BACKGROUNDS for arbs in (0, 3) for lat in LATENCIES]
    res = c.grid(cells)
    rows = []
    for s in cells:
        rs, mms = res[s], [_mm(r) for r in res[s]]
        late = sum(m["cancels_too_late"] for m in mms)
        tries = sum(m["cancel_attempts"] for m in mms)
        p, lo, hi = stats.wilson_ci(late, tries)
        base = s.with_(mm_latency="colocated")
        rows.append([
            _bg(s.background), s.arbs, s.mm_latency, _ci([m["pnl_dollars"] for m in mms]), _paired(_pnl(rs), _pnl(res[base]), s == base),
            _ci([decomposition(m, 50)["adverse_selection"] for m in mms]),
            _ci([m["race_losses"] for m in mms], 1), f"{late}/{tries}", report.ci(100 * p, 100 * lo, 100 * hi, 1) if tries else "–",
            _ci([r["market"]["races"]["races"] for r in rs], 1), f"{stats.mean([m['fills'] for m in mms]):.0f}",
        ])
    body = [
        c.design(
            f"One market maker, {STEP7}, at three latency locations (co-located ≈ µs, proximity ≈ tens of µs, remote ≈ ms; "
            "docs/SIMULATION.md), with 0 or 3 co-located latency arbitrageurs that snipe quotes left stale by a value move; "
            "10 informed traders."
        ),
        report.table(
            ["background", "arbitrageurs", "maker latency", "PnL $", "PnL − co-located (paired) $", "adverse selection 50 ms $", "maker's race losses", "cancels too late / sent", "too late (%)", "races in the market", "fills"],
            rows,
        ),
        "A race: messages from two or more participants at the same quote within 500 µs, at least one succeeding and one "
        "failing (docs/METRICS.md). A cancel is too late when the order was already gone, at the engine or at the gateway. "
        "Too-late shares are pooled over seeds with Wilson intervals.",
    ]
    return c.write("rq4", "RQ4: latency and expected PnL", "How does the market maker's latency, against fast arbitrageurs, change its PnL and race losses?", body, res)


def rq5(c: Ctx) -> Path:
    cells = [c.base.with_(background=b, makers=(5,), informed=30, informed_latency=lat) for b in BACKGROUNDS for lat in LATENCIES]
    res = c.grid(cells)
    rows = []
    for s in cells:
        mms = [_mm(r) for r in res[s]]
        adverse = [_ci([decomposition(m, h)["adverse_selection"] for m in mms]) for h in (50, 1000, 15000)]
        informed = [sum(a["pnl_dollars"] for a in r["agents"] if a["kind"] == "informed") for r in res[s]]
        base = s.with_(informed_latency="colocated")
        rows.append([
            _bg(s.background), s.informed_latency, _ci([m["pnl_dollars"] for m in mms]), _paired(_pnl(res[s]), _pnl(res[base]), s == base),
            _ci([decomposition(m, 1000)["spread_capture"] for m in mms]), *adverse, _ci(informed),
        ])
    body = [
        c.design("One GLFT market maker (step 5) against 30 informed traders (noise 0.5 tick) whose signal and orders travel at one of three latencies."),
        report.table(["background", "informed latency", "maker PnL $", "maker PnL − co-located informed (paired) $", "spread capture $", "adverse selection 50 ms $", "1 s $", "15 s $", "informed traders' PnL $"], rows),
        "Adverse selection at growing horizons shows when the informed traders' information reaches the price.",
    ]
    return c.write("rq5", "RQ5: informed traders and market-maker profitability", "Where in the maker's PnL does informed trading show up, and how does information speed matter?", body, res)


def rq7(c: Ctx) -> Path:
    regimes = [(v, n) for v in (500, 2000) for n in (0, 30)]
    cells = [c.base.with_(background=b, makers=(step,), value_ms=v, informed=n) for b in BACKGROUNDS for (v, n) in regimes for step in (2, 8)]
    res = c.grid(cells)
    rows = []
    for b in BACKGROUNDS:
        for v, n in regimes:
            static = [_mm(r)["pnl_dollars"] for r in res[c.base.with_(background=b, makers=(2,), value_ms=v, informed=n)]]
            adaptive = [_mm(r)["pnl_dollars"] for r in res[c.base.with_(background=b, makers=(8,), value_ms=v, informed=n)]]
            diff = stats.paired_ci(adaptive, static)
            rows.append([_bg(b), f"{v} ms", n, _ci(static), _ci(adaptive), report.ci(*diff), _verdict(diff[1], diff[2], "adaptive better", "static better")])
    body = [
        c.design(
            "A static market maker (step 2: mid-centred, linear inventory skew) against an adaptive one (step 8: micro-price "
            "centre, GLFT quotes with online σ, order-flow skew and a mark-out toxicity guard), in four regimes: the value "
            "moves every 500 ms (volatile) or 2 s (calm) on average, with 0 or 30 informed traders. Differences are paired on seed."
        ),
        report.table(["background", "mean value-move interval", "informed", "static PnL $", "adaptive PnL $", "adaptive − static $", "verdict (95%)"], rows),
    ]
    return c.write("rq7", "RQ7: adaptive against static market makers", "Does adapting to volatility, order flow and toxicity pay, and in which regimes?", body, res)


def rq8(c: Ctx) -> Path:
    cells = [c.base.with_(background=b, makers=(7,) * n, informed=10) for b in BACKGROUNDS for n in (1, 2, 4)]
    res = c.grid(cells)
    rows = []
    def per_maker(rs: list[dict]) -> list[float]:
        return [stats.mean([m["pnl_dollars"] for m in market_makers(r)]) for r in rs]

    for s in cells:
        rs = res[s]
        base = s.with_(makers=(7,))
        total = [sum(m["pnl_dollars"] for m in market_makers(r)) for r in rs]
        rows.append([
            _bg(s.background), len(s.makers), _ci([r["market"]["mean_spread_ticks"] for r in rs], 3), _ci([r["market"]["execution_spreads"]["effective_cents"] for r in rs], 3),
            _ci([r["market"]["ofi"][0]["depth_shares"] if r["market"]["ofi"][0] else None for r in rs], 0), _ci(per_maker(rs)),
            _paired(per_maker(rs), per_maker(res[base]), s == base), _ci(total), _ci([r["market"]["return_acf1"] for r in rs], 3),
        ])
    body = [
        c.design(f"1, 2 or 4 identical market makers, {STEP7}, competing, with 10 informed traders."),
        report.table(["background", "market makers", "time-weighted spread (ticks)", "effective spread (cents)", "top-of-book depth (shares)", "PnL per maker $", "per maker − single maker (paired) $", "total maker PnL $", "lag-1 autocorrelation of 1 s returns"], rows),
        "Depth is the event-average of (bid size + ask size)/2 at the best quotes. The last column re-measures RISKS K21 "
        "(1 s mean reversion of the anchored background, −0.14 to −0.26 without market makers). Competition effects are "
        "within-simulation comparisons; ARCHITECTURE §13 keeps causal claims about competition in simulation.",
    ]
    return c.write("rq8", "RQ8: competition and spreads", "How do spreads, depth and per-maker PnL change with the number of market makers?", body, res)


EXPERIMENTS: dict[str, Callable[[Ctx], object]] = {"rq1": rq1, "rq2": rq2, "rq3": rq3_and_6, "rq4": rq4, "rq5": rq5, "rq6": rq3_and_6, "rq7": rq7, "rq8": rq8}


def write_index(out: Path) -> Path:
    """reports/README.md: one line per generated report."""
    lines = []
    for p in sorted(out.glob("rq*.md")):
        title = p.read_text(encoding="utf-8").splitlines()[0].lstrip("#").strip()
        lines.append(f"* [{title}]({p.name}) (manifests: [{p.stem}.manifests.json]({p.stem}.manifests.json))")
    text = "\n\n".join([
        "# Research reports: simulation stage",
        report.SIMULATION_ONLY,
        "Generated by `python -m hftsim.research`, one report per research question of ARCHITECTURE §13. Each holds "
        "its design, its data and the manifests that reproduce every run. What they show, and what they do not, is "
        "in [docs/RESEARCH_RESULTS.md](../docs/RESEARCH_RESULTS.md).",
        "\n".join(lines),
    ])
    path = out / "README.md"
    path.write_text(text + "\n", encoding="utf-8")
    return path


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(prog="python -m hftsim.research", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("which", nargs="+", choices=[*EXPERIMENTS, "all"], help="research questions to run")
    p.add_argument("--seeds", type=int, default=8)
    p.add_argument("--seed", type=int, default=2026, help="first seed")
    p.add_argument("--secs", type=int, default=180)
    p.add_argument("--warmup", type=int, default=60)
    p.add_argument("--workers", type=int, default=None)
    p.add_argument("--out", type=Path, default=REPO / "reports")
    p.add_argument("--no-check", action="store_true", help="skip re-running one run per report to check its digest")
    a = p.parse_args(argv)
    c = Ctx(a.seeds, a.seed, a.secs, a.warmup, a.workers, a.out, not a.no_check)
    names = list(EXPERIMENTS) if "all" in a.which else a.which
    done: set[Callable] = set()
    for n in names:
        f = EXPERIMENTS[n]
        if f in done:
            continue
        done.add(f)
        out = f(c)
        for path in out if isinstance(out, tuple) else (out,):
            print(path, flush=True)
    print(write_index(a.out), flush=True)


if __name__ == "__main__":
    main()
